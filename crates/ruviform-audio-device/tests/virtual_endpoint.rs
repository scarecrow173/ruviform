/// Enumerates devices of one direction into pairable candidates.
/// `Err` carries the honest `NotRun` reason.
fn enumerate_devices(host: &Host, direction: Direction) -> Result<Vec<EndpointCandidate>, String> {
    let (devices, label) = match direction {
        Direction::Render => (host.output_devices(), "output"),
        Direction::Capture => (host.input_devices(), "input"),
    };
    let devices = devices.map_err(|error| format!("{label}_devices() failed: {error}"))?;
    if devices.is_empty() {
        return Err(format!("no {label} devices on this host"));
    }
    Ok(devices
        .into_iter()
        .filter_map(|device| describe_candidate(device, direction))
        .collect())
}

/// Which enumeration direction a candidate came from — selects the
/// matching format query.
#[derive(Copy, Clone)]
enum Direction {
    Render,
    Capture,
}

/// Reduces one `Device` to a candidate: name, opaque id, virtual
/// stem and the negotiated `F32` format (when one exists). Devices
/// whose `name()` fails cannot be stem-matched and are skipped with
/// a note — pairing is name-driven by contract.
fn describe_candidate(device: Box<dyn Device>, direction: Direction) -> Option<EndpointCandidate> {
    let name = match device.name() {
        Ok(name) => name,
        Err(error) => {
            eprintln!("  note: device name() failed ({error}) — skipped for pairing");
            return None;
        }
    };
    let id = device
        .id()
        .ok()
        .flatten()
        .map_or_else(|| "?".to_owned(), |device_id| format!("{device_id:?}"));
    let format = match direction {
        Direction::Render => negotiate_output_format(device.as_ref()),
        Direction::Capture => negotiate_input_format(device.as_ref()),
    };
    let stem = virtual_stem(&name);
    Some(EndpointCandidate {
        name,
        id,
        stem,
        format,
        device,
    })
}

/// Pairs each render candidate with the first still-unclaimed
/// capture candidate sharing its virtual stem. Candidates without a
/// virtual name or without a counterpart are dropped — they remain
/// visible in the enumeration notes but cannot form a pair.
fn pair_candidates(renders: Vec<EndpointCandidate>, captures: Vec<EndpointCandidate>) -> Vec<Pair> {
    let mut free: Vec<Option<EndpointCandidate>> = captures.into_iter().map(Some).collect();
    let mut pairs = Vec::new();
    for render in renders {
        let Some(stem) = &render.stem else {
            continue;
        };
        let Some(index) = free.iter().position(|candidate| {
            candidate
                .as_ref()
                .is_some_and(|capture| capture.stem.as_deref() == Some(stem.as_str()))
        }) else {
            continue;
        };
        if let Some(capture) = free[index].take() {
            pairs.push(Pair { render, capture });
        }
    }
    pairs
}

/// The case-insensitive name heuristic — kept in sync with
/// `examples/endpoint_probe.rs` by hand (see [`VIRTUAL_NAME_HINTS`]).
fn is_virtual_name(name: &str) -> bool {
    let lower = name.to_lowercase();
    VIRTUAL_NAME_HINTS.iter().any(|hint| lower.contains(hint))
}

/// Normalized product stem for pairing: lowercase, non-alphanumeric
/// split, direction tokens removed. `None` for non-virtual names or
/// a stem that normalizes to nothing.
fn virtual_stem(name: &str) -> Option<String> {
    if !is_virtual_name(name) {
        return None;
    }
    let stem = name
        .to_lowercase()
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|token| !token.is_empty())
        .filter(|token| !DIRECTION_TOKENS.contains(token))
        .collect::<Vec<_>>()
        .join(" ");
    if stem.is_empty() { None } else { Some(stem) }
}

/// One full round-trip attempt for a single pair: negotiate → open →
/// stream → observe → oracle → lifecycle. `Err` carries the failure
/// list — every violation found, not just the first.
fn run_round_trip(pair: Pair) -> Result<(), Vec<String>> {
    let Pair { render, capture } = pair;
    eprintln!(
        "  render: \"{}\" id={} | capture: \"{}\" id={}",
        render.name, render.id, capture.name, capture.id
    );
    let Some(in_format) = capture.format else {
        return Err(vec!["no F32-openable input format".to_owned()]);
    };
    let Some(out_format) = render.format else {
        return Err(vec!["no F32-openable output format".to_owned()]);
    };
    eprintln!("  negotiated in={in_format:?} out={out_format:?}");

    let probe = Arc::new(Probe::new(&in_format, &out_format));
    let in_stream = match open_input_with_fallback(capture.device.as_ref(), in_format, &probe) {
        Ok(stream) => stream,
        Err(error) => return Err(vec![format!("input open failed: {error}")]),
    };
    let out_stream = match open_output_with_fallback(
        render.device.as_ref(),
        out_format,
        &probe,
        out_format.sample_rate.get(),
    ) {
        Ok(stream) => stream,
        Err(error) => return Err(vec![format!("output open failed: {error}")]),
    };

    let in_domain = in_stream.clock_domain();
    let out_domain = out_stream.clock_domain();
    probe
        .in_expected_domain
        .store(in_domain.get(), Ordering::Relaxed);
    eprintln!(
        "  in stream: format={:?} buffer_size={:?} domain={in_domain:?} latency={:?}",
        in_stream.format(),
        in_stream.buffer_size(),
        in_stream.input_latency(),
    );
    eprintln!(
        "  out stream: format={:?} buffer_size={:?} domain={out_domain:?} latency={:?}",
        out_stream.format(),
        out_stream.buffer_size(),
        out_stream.output_latency(),
    );

    if let Err(error) = in_stream.start().and_then(|()| out_stream.start()) {
        return Err(vec![format!("stream start failed: {error}")]);
    }
    thread::sleep(Duration::from_secs(CAPTURE_SECONDS));
    let lifecycle = run_lifecycle(&probe, &*in_stream, &*out_stream);
    drop(in_stream);
    drop(out_stream);

    let mut failures = analyze(&probe, &in_format, in_domain, out_domain);
    failures.extend(lifecycle);
    print_pair_evidence(&probe);
    if failures.is_empty() {
        Ok(())
    } else {
        Err(failures)
    }
}

/// Stop → post-stop queries → restart → re-stop, collecting every
/// lifecycle violation as a string (recorded, then gated with the
/// rest of the failure list).
fn run_lifecycle(
    probe: &Probe,
    in_stream: &dyn InputStream,
    out_stream: &dyn OutputStream,
) -> Vec<String> {
    let mut lifecycle = Vec::new();
    for (label, result) in [
        ("input stop", in_stream.stop()),
        ("output stop", out_stream.stop()),
    ] {
        if let Err(error) = result {
            lifecycle.push(format!("{label} failed: {error}"));
        }
    }
    for (label, result) in [
        ("in buffer_size", in_stream.buffer_size().map(|_| ())),
        ("in now", in_stream.now().map(|_| ())),
        ("out buffer_size", out_stream.buffer_size().map(|_| ())),
        ("out now", out_stream.now().map(|_| ())),
    ] {
        if let Err(error) = result {
            lifecycle.push(format!("post-stop {label} query failed: {error}"));
        }
    }
    // Epoch boundary: a stop/start transition legitimately re-anchors the
    // OS-side timestamp epoch (on shared-mode render streams audiodg
    // re-derives the position↔QPC correlation from its own packet epoch —
    // there is no driver-supplied output timestamp to keep it continuous),
    // so the first callbacks of a restarted run can land below the last
    // pre-stop timestamp without being a defect. Splitting the baseline
    // here keeps the regression oracle measuring what it means to —
    // monotonicity inside one continuous run — while the reset itself is
    // counted as lifecycle evidence.
    probe.in_last_callback_ns.store(i64::MIN, Ordering::Relaxed);
    probe
        .out_last_callback_ns
        .store(i64::MIN, Ordering::Relaxed);
    probe
        .in_timestamp_epoch_resets
        .fetch_add(1, Ordering::Relaxed);
    probe
        .out_timestamp_epoch_resets
        .fetch_add(1, Ordering::Relaxed);
    // Boundary marker: the callback count at the split — regression
    // indices below it belong to run 1, above it to run 2.
    probe.in_epoch_boundary_cb.store(
        probe.in_callbacks.load(Ordering::Relaxed) as u64,
        Ordering::Relaxed,
    );
    probe.out_epoch_boundary_cb.store(
        probe.out_callbacks.load(Ordering::Relaxed) as u64,
        Ordering::Relaxed,
    );
    // Restart probe: a stream that cannot restart after stop is a
    // lifecycle contract violation.
    match in_stream.start().and_then(|()| out_stream.start()) {
        Ok(()) => {
            thread::sleep(RESTART_SETTLE);
            for (label, result) in [
                ("input re-stop", in_stream.stop()),
                ("output re-stop", out_stream.stop()),
            ] {
                if let Err(error) = result {
                    lifecycle.push(format!("{label} failed: {error}"));
                }
            }
        }
        Err(error) => lifecycle.push(format!("restart start failed: {error}")),
    }
    lifecycle
}

/// Opens the input stream, first requesting `BufferSize::Fixed(480)`;
/// a `DeviceError::UnsupportedConfig` retry with `BufferSize::Default`
/// separates "fixed size rejected" from "stream cannot open".
fn open_input_with_fallback(
    device: &dyn Device,
    format: AudioFormat,
    probe: &Arc<Probe>,
) -> Result<Box<dyn InputStream>, DeviceError> {
    let requested = InputStreamConfig {
        format,
        buffer_size: BufferSize::Fixed(REQUESTED_FRAMES),
    };
    match device.open_input_stream(
        &requested,
        input_data_callback(probe),
        input_error_callback(probe),
    ) {
        Ok(stream) => Ok(stream),
        Err(DeviceError::UnsupportedConfig) => {
            eprintln!(
                "  open input Fixed({REQUESTED_FRAMES}) → UnsupportedConfig; retrying Default"
            );
            let fallback = InputStreamConfig {
                format,
                buffer_size: BufferSize::Default,
            };
            device.open_input_stream(
                &fallback,
                input_data_callback(probe),
                input_error_callback(probe),
            )
        }
        Err(error) => Err(error),
    }
}

/// Output-direction mirror of [`open_input_with_fallback`].
fn open_output_with_fallback(
    device: &dyn Device,
    format: AudioFormat,
    probe: &Arc<Probe>,
    rate_hz: u32,
) -> Result<Box<dyn OutputStream>, DeviceError> {
    let requested = OutputStreamConfig {
        format,
        buffer_size: BufferSize::Fixed(REQUESTED_FRAMES),
    };
    match device.open_output_stream(
        &requested,
        output_data_callback(probe, rate_hz),
        output_error_callback(probe),
    ) {
        Ok(stream) => Ok(stream),
        Err(DeviceError::UnsupportedConfig) => {
            eprintln!(
                "  open output Fixed({REQUESTED_FRAMES}) → UnsupportedConfig; retrying Default"
            );
            let fallback = OutputStreamConfig {
                format,
                buffer_size: BufferSize::Default,
            };
            device.open_output_stream(
                &fallback,
                output_data_callback(probe, rate_hz),
                output_error_callback(probe),
            )
        }
        Err(error) => Err(error),
    }
}

/// The input RT data callback — thin closure over
/// [`observe_input`], which carries the observation body.
fn input_data_callback(probe: &Arc<Probe>) -> InputDataCallback {
    let probe = Arc::clone(probe);
    Box::new(move |input, info| observe_input(&probe, input, info))
}

/// Input-callback observation body — mirrors
/// `real_input_e2e.rs`'s discipline (relaxed atomics, one bounded
/// slab pass) plus the bounded channel-0 handoff copy.
fn observe_input(probe: &Probe, input: AudioBufferView<'_, f32>, info: InputCallbackInfo) {
    let frames = input.frames();
    let channels = input.channels();
    let callback_index = probe.in_callbacks.fetch_add(1, Ordering::Relaxed) as u64;
    probe.in_frames.fetch_add(frames as u64, Ordering::Relaxed);
    probe.in_min_frames.fetch_min(frames, Ordering::Relaxed);
    probe.in_max_frames.fetch_max(frames, Ordering::Relaxed);
    if channels != probe.in_expected_channels {
        probe.in_channel_mismatches.fetch_add(1, Ordering::Relaxed);
    }

    let callback_ns = info.timestamp.callback.value();
    let previous = probe
        .in_last_callback_ns
        .fetch_max(callback_ns, Ordering::Relaxed);
    if callback_ns < previous {
        let slot = probe
            .in_timestamp_regressions
            .fetch_add(1, Ordering::Relaxed);
        if slot < REGRESSION_INDEX_SLOTS {
            probe.in_regression_cbs[slot].store(callback_index, Ordering::Relaxed);
        }
        probe
            .in_regression_first_cb
            .fetch_min(callback_index, Ordering::Relaxed);
        probe
            .in_regression_last_cb
            .fetch_max(callback_index, Ordering::Relaxed);
        probe
            .in_regression_max_backstep_ns
            .fetch_min(callback_ns - previous, Ordering::Relaxed);
    }
    if info.clock_domain.get() != probe.in_expected_domain.load(Ordering::Relaxed) {
        probe.in_domain_mismatches.fetch_add(1, Ordering::Relaxed);
    }
    match info.timestamp.capture {
        Some(capture) => {
            probe.in_capture_some.fetch_add(1, Ordering::Relaxed);
            // `callback - capture` = effective input latency —
            // recorded, not asserted. A negative delta is an ordering
            // violation: the capture instant must precede delivery.
            let delta_ns = callback_ns - capture.time.value();
            probe
                .in_latency_min_ns
                .fetch_min(delta_ns, Ordering::Relaxed);
            probe
                .in_latency_max_ns
                .fetch_max(delta_ns, Ordering::Relaxed);
            // Summed clamped to ±1000 s — an unclamped bogus instant
            // would wrap i64 and poison the record.
            probe.in_latency_sum_ns.fetch_add(
                delta_ns.clamp(-1_000_000_000_000, 1_000_000_000_000),
                Ordering::Relaxed,
            );
            probe.in_latency_count.fetch_add(1, Ordering::Relaxed);
            if delta_ns < 0 {
                probe
                    .in_capture_order_violations
                    .fetch_add(1, Ordering::Relaxed);
            }
        }
        None => {
            probe.in_capture_none.fetch_add(1, Ordering::Relaxed);
        }
    }
    if let Some(position) = info.frame_position {
        probe.in_position_some.fetch_add(1, Ordering::Relaxed);
        // The next callback's first-frame position must equal this
        // packet's `position + frames` — contiguous capture-clock
        // spans unless a discontinuity was reported. Callbacks are
        // serial per stream.
        let expected = probe.in_expected_position.load(Ordering::Relaxed);
        if expected != u64::MAX && position != expected {
            probe.in_position_gaps.fetch_add(1, Ordering::Relaxed);
        }
        probe
            .in_expected_position
            .store(position.wrapping_add(frames as u64), Ordering::Relaxed);
        if probe.in_first_position.load(Ordering::Relaxed) == u64::MAX {
            probe.in_first_position.store(position, Ordering::Relaxed);
        }
        probe
            .in_last_position
            .fetch_max(position, Ordering::Relaxed);
    }

    // One bounded pass over the slab: non-finite scan + peak.
    let mut non_finite = 0_usize;
    let mut peak = 0.0_f32;
    for sample in input.data() {
        if sample.is_finite() {
            peak = peak.max(sample.abs());
        } else {
            non_finite += 1;
        }
    }
    probe.in_non_finite.fetch_add(non_finite, Ordering::Relaxed);
    // Non-negative `f32` bit patterns order monotonically —
    // `fetch_max` on the bits is an exact atomic max.
    probe
        .in_peak_bits
        .fetch_max(peak.to_bits(), Ordering::Relaxed);

    // Bounded handoff copy — `try_lock` never blocks; a contended or
    // full buffer is counted, not silently lost.
    match probe.capture.try_lock() {
        Ok(mut buf) => buf.push(&input),
        Err(_) => {
            probe.capture_lock_failures.fetch_add(1, Ordering::Relaxed);
        }
    }
}

/// The output RT data callback — thin closure over
/// [`observe_output`].
fn output_data_callback(probe: &Arc<Probe>, rate_hz: u32) -> OutputDataCallback {
    let probe = Arc::clone(probe);
    Box::new(move |out, info| observe_output(&probe, out, info, rate_hz))
}

/// Output-callback observation body — writes the deterministic
/// stimulus ([`signal_sample`], identical on every channel) and
/// records the same observation discipline as the input side.
fn observe_output(
    probe: &Probe,
    mut out: AudioBufferViewMut<'_, f32>,
    info: OutputCallbackInfo,
    rate_hz: u32,
) {
    let frames = out.frames();
    let callback_index = probe.out_callbacks.fetch_add(1, Ordering::Relaxed) as u64;
    probe.out_frames.fetch_add(frames as u64, Ordering::Relaxed);
    probe.out_min_frames.fetch_min(frames, Ordering::Relaxed);
    probe.out_max_frames.fetch_max(frames, Ordering::Relaxed);
    if out.channels() != probe.out_expected_channels {
        probe.out_channel_mismatches.fetch_add(1, Ordering::Relaxed);
    }

    let callback_ns = info.timestamp.callback.value();
    let previous = probe
        .out_last_callback_ns
        .fetch_max(callback_ns, Ordering::Relaxed);
    if callback_ns < previous {
        let slot = probe
            .out_timestamp_regressions
            .fetch_add(1, Ordering::Relaxed);
        if slot < REGRESSION_INDEX_SLOTS {
            probe.out_regression_cbs[slot].store(callback_index, Ordering::Relaxed);
        }
        probe
            .out_regression_first_cb
            .fetch_min(callback_index, Ordering::Relaxed);
        probe
            .out_regression_last_cb
            .fetch_max(callback_index, Ordering::Relaxed);
        probe
            .out_regression_max_backstep_ns
            .fetch_min(callback_ns - previous, Ordering::Relaxed);
    }
    match info.timestamp.playback {
        Some(playback) => {
            probe.out_playback_some.fetch_add(1, Ordering::Relaxed);
            // `playback - callback` = effective output latency —
            // recorded, not asserted.
            let delta_ns = playback.value() - callback_ns;
            probe
                .out_latency_min_ns
                .fetch_min(delta_ns, Ordering::Relaxed);
            probe
                .out_latency_max_ns
                .fetch_max(delta_ns, Ordering::Relaxed);
            probe.out_latency_sum_ns.fetch_add(
                delta_ns.clamp(-1_000_000_000_000, 1_000_000_000_000),
                Ordering::Relaxed,
            );
            probe.out_latency_count.fetch_add(1, Ordering::Relaxed);
        }
        None => {
            probe.out_playback_none.fetch_add(1, Ordering::Relaxed);
        }
    }

    // Same signal on every channel: the absolute frame index keeps
    // marker positions rate-true across variable-size callbacks.
    // `fetch_add` reserves this callback's range — callbacks are
    // serial per stream, so the returned base is exact.
    let base = probe
        .out_render_cursor
        .fetch_add(frames as u64, Ordering::Relaxed);
    let marker_period = marker_period_frames(rate_hz);
    for channel in 0..out.channels() {
        if let Some(samples) = out.channel_mut(channel) {
            for (offset, sample) in samples.iter_mut().enumerate() {
                *sample = signal_sample(base + offset as u64, rate_hz, marker_period);
            }
        }
    }
}

/// The input error callback — counts events, records the latest error
/// kind and tallies xruns/discontinuities/invalidations without
/// allocating (mirrors `real_input_e2e.rs`).
fn input_error_callback(probe: &Arc<Probe>) -> InputErrorCallback {
    let probe = Arc::clone(probe);
    Box::new(move |error: DeviceError| {
        probe.in_errors.fetch_add(1, Ordering::Relaxed);
        probe
            .in_last_error_kind
            .store(error_kind_code(error), Ordering::Relaxed);
        if error == DeviceError::Xrun {
            probe.in_xruns.fetch_add(1, Ordering::Relaxed);
        }
        if error == DeviceError::ClockDiscontinuity {
            probe.in_discontinuities.fetch_add(1, Ordering::Relaxed);
        }
        if error == DeviceError::StreamInvalidated {
            probe.in_invalidated.fetch_add(1, Ordering::Relaxed);
        }
    })
}

/// The output error callback — same discipline, output direction.
fn output_error_callback(probe: &Arc<Probe>) -> OutputErrorCallback {
    let probe = Arc::clone(probe);
    Box::new(move |error: DeviceError| {
        probe.out_errors.fetch_add(1, Ordering::Relaxed);
        probe
            .out_last_error_kind
            .store(error_kind_code(error), Ordering::Relaxed);
        if error == DeviceError::Xrun {
            probe.out_xruns.fetch_add(1, Ordering::Relaxed);
        }
        if error == DeviceError::StreamInvalidated {
            probe.out_invalidated.fetch_add(1, Ordering::Relaxed);
        }
    })
}

/// Stable numeric codes for [`DeviceError`] kinds so the most recent
/// error fits an [`AtomicUsize`]. `DeviceError` is `#[non_exhaustive]`
/// — future variants land on `99`.
fn error_kind_code(error: DeviceError) -> usize {
    match error {
        DeviceError::DeviceNotFound => 1,
        DeviceError::DeviceBusy => 2,
        DeviceError::UnsupportedConfig => 3,
        DeviceError::Unsupported => 4,
        DeviceError::Xrun => 5,
        DeviceError::RealtimeDenied => 6,
        DeviceError::StreamInvalidated => 7,
        DeviceError::ClockDiscontinuity => 8,
        DeviceError::Backend(_) => 9,
        _ => 99,
    }
}

/// Marker period in frames at `rate_hz` — 100 ms, integer-exact.
fn marker_period_frames(rate_hz: u32) -> u64 {
    (u64::from(rate_hz) * MARKER_PERIOD_MS / 1_000).max(1)
}

/// One stimulus sample at absolute `frame` — the *independent*
/// oracle's generator: it defines what was sent, never observes the
/// adapter. 440 Hz sine + a [`MARKER_BURST_FRAMES`]-frame 0.70
/// impulse burst every [`MARKER_PERIOD_MS`] ms; peak |sine+marker|
/// stays <= 0.90, no clipping.
#[expect(clippy::cast_precision_loss, clippy::cast_possible_truncation)]
fn signal_sample(frame: u64, rate_hz: u32, marker_period: u64) -> f32 {
    let phase = frame as f64 / f64::from(rate_hz);
    let sine = SINE_AMPLITUDE * (TAU * SINE_HZ * phase).sin();
    let marker = if frame % marker_period < MARKER_BURST_FRAMES {
        MARKER_AMPLITUDE
    } else {
        0.0
    };
    (sine + marker) as f32
}

/// `u64 → f64` for oracle math — the precision loss is immaterial at
/// frame counts far below 2^53; one expect site instead of one per
/// call site.
#[expect(clippy::cast_precision_loss)]
fn frames_f64(frames: u64) -> f64 {
    frames as f64
}

/// Effective regression count: raw regressions minus those inside
/// the per-epoch startup grace window (see
/// [`EPOCH_START_GRACE_CALLBACKS`]). `boundary_cb` splits the run
/// into epoch 1 (indices below it) and epoch 2 (at/above it);
/// `u64::MAX` means the restart never ran and the whole run is one
/// epoch. Only the first [`REGRESSION_INDEX_SLOTS`] regressions have
/// a recorded index — anything past that cannot be classified and
/// stays fatal.
fn effective_regressions(raw: usize, slots: &[AtomicU64], boundary_cb: u64) -> usize {
    let mut transients = 0;
    for slot in slots.iter().take(raw) {
        let cb = slot.load(Ordering::Relaxed);
        let epoch_start = if cb < boundary_cb { 0 } else { boundary_cb };
        if cb.saturating_sub(epoch_start) < EPOCH_START_GRACE_CALLBACKS {
            transients += 1;
        }
    }
    raw - transients
}

/// Control-thread analysis: callback-contract violations first,
/// then the independent-oracle checks (marker spacing, level, tone).
/// Returns the failure list — empty means the pair passed.
fn analyze(
    probe: &Probe,
    in_format: &AudioFormat,
    in_domain: ClockDomainId,
    out_domain: ClockDomainId,
) -> Vec<String> {
    let mut failures = Vec::new();
    let in_cb = probe.in_callbacks.load(Ordering::Relaxed);
    let out_cb = probe.out_callbacks.load(Ordering::Relaxed);
    if in_cb == 0 || out_cb == 0 {
        failures.push(format!(
            "open+start but zero data callbacks (in={in_cb} out={out_cb})"
        ));
        return failures;
    }
    if probe.in_frames.load(Ordering::Relaxed) == 0 {
        failures.push("input stream delivered zero frames".to_owned());
    }

    // Callback-contract violations — hard gates.
    for (label, count) in [
        (
            "input channel mismatches",
            probe.in_channel_mismatches.load(Ordering::Relaxed),
        ),
        (
            "output channel mismatches",
            probe.out_channel_mismatches.load(Ordering::Relaxed),
        ),
        (
            "input timestamp regressions",
            effective_regressions(
                probe.in_timestamp_regressions.load(Ordering::Relaxed),
                &probe.in_regression_cbs,
                probe.in_epoch_boundary_cb.load(Ordering::Relaxed),
            ),
        ),
        (
            "output timestamp regressions",
            effective_regressions(
                probe.out_timestamp_regressions.load(Ordering::Relaxed),
                &probe.out_regression_cbs,
                probe.out_epoch_boundary_cb.load(Ordering::Relaxed),
            ),
        ),
        (
            "input clock-domain mismatches",
            probe.in_domain_mismatches.load(Ordering::Relaxed),
        ),
        (
            "capture-after-callback order violations",
            probe.in_capture_order_violations.load(Ordering::Relaxed),
        ),
        (
            "non-finite input samples",
            probe.in_non_finite.load(Ordering::Relaxed),
        ),
    ] {
        if count > 0 {
            failures.push(format!("{label}: {count}"));
        }
    }
    // A frame-position break must be notified as ClockDiscontinuity —
    // more unexplained jumps than notifications is a contract break.
    let position_gaps = probe.in_position_gaps.load(Ordering::Relaxed);
    let discontinuities = probe.in_discontinuities.load(Ordering::Relaxed);
    if position_gaps > discontinuities {
        failures.push(format!(
            "unnotified frame-position discontinuity: gaps={position_gaps} discontinuities={discontinuities}"
        ));
    }

    // Independent oracle on the captured channel-0 PCM.
    let rate = in_format.sample_rate.get();
    let buf = capture_buffer(probe);
    let samples = &buf.data[..buf.len.min(buf.data.len())];
    if samples.len() < min_oracle_samples(rate) {
        failures.push(format!(
            "insufficient captured audio for oracle: {} frames at {rate} Hz",
            samples.len()
        ));
        return failures;
    }
    failures.extend(oracle_markers(samples, rate));
    failures.extend(oracle_level(samples, rate));
    failures.extend(oracle_tone(samples, rate));

    // Domain agreement is recorded, never gated — `UNKNOWN` domains
    // are an honest backend answer, not a failure.
    eprintln!(
        "  clock domains: in={in_domain:?} out={out_domain:?} same_clock_domain={}",
        same_clock_domain(in_domain, out_domain)
    );
    failures
}

/// Minimum captured frames before the oracle runs — ~0.5 s, enough
/// for several marker periods even after cable latency eats the head.
fn min_oracle_samples(rate_hz: u32) -> usize {
    usize::try_from(u64::from(rate_hz) / 2).unwrap_or(usize::MAX)
}

/// Locks the capture buffer on the control thread. A poisoned mutex
/// means a callback panicked — the data is still recovered via
/// `into_inner`, and the callback-contract checks above already
/// surface the missing observations as failures.
fn capture_buffer(probe: &Probe) -> MutexGuard<'_, CaptureBuf> {
    probe
        .capture
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
}

/// Marker-spacing oracle: detect `|x| > MARKER_THRESHOLD` peaks with
/// a refractory window, then require >= `MARKER_MIN_COUNT` markers
/// whose mean interval matches 100 ms within tolerance.
fn oracle_markers(samples: &[f32], rate_hz: u32) -> Vec<String> {
    let refractory = (u64::from(rate_hz) * MARKER_REFRACTORY_MS / 1_000).max(1);
    let mut markers: Vec<u64> = Vec::new();
    let mut next_allowed = 0_u64;
    for (index, &sample) in samples.iter().enumerate() {
        let frame = index as u64;
        if sample.abs() > MARKER_THRESHOLD && frame >= next_allowed {
            markers.push(frame);
            next_allowed = frame + refractory;
        }
    }
    if markers.len() < MARKER_MIN_COUNT {
        return vec![format!(
            "marker oracle: only {} markers detected (need {})",
            markers.len(),
            MARKER_MIN_COUNT
        )];
    }
    let intervals: Vec<f64> = markers
        .windows(2)
        .map(|pair| frames_f64(pair[1] - pair[0]) / f64::from(rate_hz))
        .collect();
    let mean = intervals.iter().sum::<f64>() / frames_f64(intervals.len() as u64);
    let expected = frames_f64(MARKER_PERIOD_MS) / 1_000.0;
    if (mean - expected).abs() > expected * MARKER_INTERVAL_TOLERANCE {
        return vec![format!(
            "marker oracle: mean interval {mean:.4}s deviates from {expected}s"
        )];
    }
    Vec::new()
}

/// Level oracle: observed channel-0 RMS vs the expected RMS of the
/// stimulus computed independently at the capture rate. SRC is
/// assumed unity-gain; the band is provisional.
fn oracle_level(samples: &[f32], rate_hz: u32) -> Vec<String> {
    let observed = rms(samples);
    let expected = expected_signal_rms(rate_hz);
    let ratio = if expected > 0.0 {
        observed / expected
    } else {
        0.0
    };
    eprintln!(
        "  oracle level: observed_rms={observed:.4} expected_rms={expected:.4} ratio={ratio:.3}"
    );
    if !(MIN_LEVEL_RATIO..=MAX_LEVEL_RATIO).contains(&ratio) {
        return vec![format!(
            "level oracle: rms ratio {ratio:.3} outside [{MIN_LEVEL_RATIO}, {MAX_LEVEL_RATIO}]"
        )];
    }
    Vec::new()
}

/// Spectral oracle: Goertzel power at 440 Hz vs total power —
/// proves the tonal component survived, not just the impulses.
fn oracle_tone(samples: &[f32], rate_hz: u32) -> Vec<String> {
    let ratio = tone_ratio(samples, rate_hz, SINE_HZ);
    eprintln!("  oracle tone: 440Hz share of power={ratio:.3}");
    if ratio < MIN_TONE_RATIO {
        return vec![format!(
            "tone oracle: 440 Hz share {ratio:.3} below {MIN_TONE_RATIO}"
        )];
    }
    Vec::new()
}

/// RMS of a sample slice.
fn rms(samples: &[f32]) -> f64 {
    if samples.is_empty() {
        return 0.0;
    }
    let sum_sq: f64 = samples
        .iter()
        .map(|&sample| f64::from(sample) * f64::from(sample))
        .sum();
    (sum_sq / frames_f64(samples.len() as u64)).sqrt()
}

/// Expected stimulus RMS computed independently: [`signal_sample`]
/// over enough marker periods to average the burst duty cycle.
#[expect(clippy::cast_precision_loss)]
fn expected_signal_rms(rate_hz: u32) -> f64 {
    let period = marker_period_frames(rate_hz);
    let frames = period.saturating_mul(100).max(1);
    let mut sum_sq = 0.0_f64;
    for frame in 0..frames {
        let sample = signal_sample(frame, rate_hz, period);
        sum_sq += f64::from(sample) * f64::from(sample);
    }
    (sum_sq / frames as f64).sqrt()
}

/// Goertzel single-frequency power ratio: tone mean-square at
/// `freq_hz` divided by total mean-square.
fn tone_ratio(samples: &[f32], rate_hz: u32, freq_hz: f64) -> f64 {
    let n = samples.len();
    if n == 0 {
        return 0.0;
    }
    let omega = TAU * freq_hz / f64::from(rate_hz);
    let coeff = 2.0 * omega.cos();
    let (mut s_prev2, mut s_prev1) = (0.0_f64, 0.0_f64);
    for &sample in samples {
        let s0 = f64::from(sample) + coeff * s_prev1 - s_prev2;
        s_prev2 = s_prev1;
        s_prev1 = s0;
    }
    let power = s_prev1 * s_prev1 + s_prev2 * s_prev2 - coeff * s_prev1 * s_prev2;
    let total: f64 = samples
        .iter()
        .map(|&sample| f64::from(sample) * f64::from(sample))
        .sum();
    let nf = frames_f64(n as u64);
    if total <= 0.0 {
        return 0.0;
    }
    // One-sided tone mean-square = 2·|X|²/N²; ratio vs total
    // mean-square = total/N simplifies to 2·power/(N·total).
    2.0 * power / (nf * total)
}

