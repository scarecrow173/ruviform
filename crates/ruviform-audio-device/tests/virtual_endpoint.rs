//! Virtual-endpoint streaming verifier — Issue #629 fourth slice.
//!
//! `#[ignore]`-gated manual real-device lane, gated on the
//! `real-device` feature exactly like `real_input_e2e.rs`: default
//! `cargo test` compiles this file empty, and the intended entry
//! point is `mise run test-audio-virtual-endpoint` (equivalent to
//! `cargo test -p ruviform-audio-device --features real-device
//! --test virtual_endpoint -- --ignored --test-threads=1`). The lane
//! is a provisioning-dependent manual opt-in — never CI; unprovisioned
//! hosts report `verdict: NotRun` (fail-closed).
//!
//! What it verifies when a virtual audio pair is provisioned:
//!
//! - production `DeviceEnumerator`/`Device` enumeration finds a
//!   render↔capture *pair candidate* — the same name heuristic as
//!   `examples/endpoint_probe.rs` (`is_virtual_name`) plus a
//!   direction-word-stripped stem match ("CABLE Input" ↔ "CABLE
//!   Output", "Voicemeeter Input" ↔ "Voicemeeter Output", …).
//! - `open_output_stream`/`open_input_stream` negotiate an `F32`
//!   format and actually deliver callbacks — open+start with zero
//!   callbacks is a FAIL, not a pass.
//! - a deterministic stimulus (440 Hz sine + 100 ms impulse-marker
//!   bursts, generated by the independent [`signal_sample`] oracle —
//!   never by the adapter under test) rendered through the output
//!   stream is observed on the input stream: marker spacing, level
//!   ratio and tonal concentration are compared with tolerances —
//!   never bit-exact, because virtual cables run an internal
//!   sample-rate converter (VB-CABLE family: 48 kHz internal + SRC).
//! - callback contract observations mirror `real_input_e2e.rs`:
//!   frame counts, timestamp monotonicity within each continuous
//!   run (the OS legitimately re-anchors its timestamp epoch across
//!   a stop → restart boundary — counted as `epoch_resets`, not as
//!   regressions — and re-derives the position↔QPC correlation at
//!   every `start()`, so epoch-start callbacks get a bounded grace
//!   window), clock-domain agreement, `capture <= callback`
//!   ordering, `frame_position` continuity, non-finite scan,
//!   latency records, error counters, and a
//!   stop → query → restart → stop lifecycle check.
//!
//! Fail-closed contract: with no pair candidate (the common case —
//! nothing provisioned) the test prints `verdict: NotRun` and
//! returns without asserting. A name match is a *candidate*, not
//! proof of a virtual endpoint — a Pass here is OS-L1 "real OS API
//! round-trip" evidence, never `environment_kind=
//! virtual-os-endpoint`. Controller-armed fault cases in this file
//! exercise `StreamInvalidated`, permission denial and bounded xrun
//! observation for AC5; unarmed canonical-lane runs keep those cases
//! explicitly inactive, and ordinary round-trip error events are
//! recorded, not gated.

