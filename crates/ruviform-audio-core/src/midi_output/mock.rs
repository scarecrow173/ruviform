//! Deterministic scripted MIDI output backend — the send-direction
//! counterpart of `midi_input::mock` (Issue #629, 2nd slice).
//!
//! This is **not a backend**: it is the controlled sink the port
//! contract tests and future bridge/engine tests drive — the same
//! `Arc<Mutex<…>>` shape as the input fixture. A test registers ports
//! with [`MockBackend::add_port`], opens them through the
//! [`MidiOutputEnumerator`] surface, sends [`MidiEvent`]s and `SysEx`
//! byte strings, then reads back exactly what the subscription
//! accepted — the Expected/Observed pair the evidence vocabulary
//! requires (the expectation lives in the test, never generated by
//! the code under test).
//!
//! Fault injection mirrors the input fixture: `fail_next_open` and
//! `fail_next_send` arm one-shot errors consumed by the next call, so
//! transient refusals and mid-stream failures are scriptable without
//! an OS.
//!
//! **RT contract:** non-RT fixture — every method may lock and
//! allocate; nothing here runs on the audio thread.

use std::sync::{Arc, Mutex};

use ruviform_media_core::MidiEvent;

use crate::device::{DeviceError, DeviceResult};

use super::{MidiOutput, MidiOutputEnumerator, MidiOutputInfo, MidiOutputPort};

/// Per-port scripted state shared by the enumerator's port objects,
/// the opened subscription and the test-side handle.
struct PortState {
    info: MidiOutputInfo,
    sent: Vec<MidiEvent>,
    sent_sysex: Vec<Vec<u8>>,
    opened: bool,
    closed: bool,
    open_error: Option<DeviceError>,
    send_error: Option<DeviceError>,
}

/// Deterministic scripted MIDI output backend — the
/// [`MidiOutputEnumerator`] implementation.
///
/// Register ports with [`Self::add_port`]; each returned [`MockPort`]
/// is simultaneously the `MidiOutputPort` trait object handed to the
/// engine and the test-side observation/injection handle — the same
/// `Arc`-backed state, mirroring how a real adapter's port handle
/// stays live while its subscription is open.
///
/// ```
/// use ruviform_audio_core::midi_output::mock::MockBackend;
/// use ruviform_audio_core::midi_output::{
///     MidiOutputEnumerator, MidiOutputInfo, MidiPortCapabilities, MidiPortOrigin,
/// };
///
/// let mut backend = MockBackend::new();
/// let port = backend.add_port(MidiOutputInfo::new(
///     "mock-out-0".to_owned(),
///     "Mock Out 0".to_owned(),
///     MidiPortOrigin::Virtual,
///     MidiPortCapabilities::midi1_unstamped(),
/// ));
/// let ports = backend.output_ports().unwrap();
/// assert_eq!(ports.len(), 1);
/// assert_eq!(port.info().id, "mock-out-0");
/// ```
#[derive(Default)]
pub struct MockBackend {
    ports: Vec<MockPort>,
}

impl MockBackend {
    /// An empty backend — register ports with [`Self::add_port`].
    #[must_use]
    pub fn new() -> Self {
        Self { ports: Vec::new() }
    }

    /// Registers a scripted port and returns its test-side handle.
    ///
    /// **RT contract:** non-RT — allocates.
    pub fn add_port(&mut self, info: MidiOutputInfo) -> MockPort {
        let port = MockPort::new(info);
        self.ports.push(port.clone());
        port
    }

    /// Number of registered ports — test convenience so assertions do
    /// not need to enumerate just to count.
    #[must_use]
    pub fn port_count(&self) -> usize {
        self.ports.len()
    }
}

impl MidiOutputEnumerator for MockBackend {
    /// The registered ports in registration order. Never fails —
    /// enumeration of a scripted backend cannot hit an OS error.
    fn output_ports(&self) -> DeviceResult<Vec<Box<dyn MidiOutputPort>>> {
        Ok(self
            .ports
            .iter()
            .cloned()
            .map(|port| Box::new(port) as Box<dyn MidiOutputPort>)
            .collect())
    }
}

/// One scripted port — the `MidiOutputPort` trait object *and* the
/// test-side observation/injection handle (clone shares the state).
#[derive(Clone)]
pub struct MockPort {
    state: Arc<Mutex<PortState>>,
}

impl MockPort {
    fn new(info: MidiOutputInfo) -> Self {
        Self {
            state: Arc::new(Mutex::new(PortState {
                info,
                sent: Vec::new(),
                sent_sysex: Vec::new(),
                opened: false,
                closed: false,
                open_error: None,
                send_error: None,
            })),
        }
    }

    fn lock(&self) -> std::sync::MutexGuard<'_, PortState> {
        self.state.lock().expect("mock MIDI port state poisoned")
    }

    /// The port's declared identity — same value `info()` reports.
    #[must_use]
    pub fn info(&self) -> MidiOutputInfo {
        self.lock().info.clone()
    }

    /// Channel-voice events the subscription accepted, in send order —
    /// the observed half of the Expected/Observed pair.
    #[must_use]
    pub fn sent_events(&self) -> Vec<MidiEvent> {
        self.lock().sent.clone()
    }

    /// `SysEx` byte strings the subscription accepted, in send order.
    #[must_use]
    pub fn sent_sysex(&self) -> Vec<Vec<u8>> {
        self.lock().sent_sysex.clone()
    }

    /// Total accepted sends (events + `SysEx` strings).
    #[must_use]
    pub fn sent_count(&self) -> usize {
        let state = self.lock();
        state.sent.len() + state.sent_sysex.len()
    }

    /// Drops the recorded sends — test convenience for phased
    /// scenarios (send batch A, assert, `clear_sent`, send batch B).
    pub fn clear_sent(&self) {
        let mut state = self.lock();
        state.sent.clear();
        state.sent_sysex.clear();
    }

    /// Make the *next* `open` fail with `error` (one-shot — consumed
    /// by the failing call, so a retry can succeed).
    pub fn fail_next_open(&self, error: DeviceError) {
        self.lock().open_error = Some(error);
    }

    /// Make the *next* `send`/`send_sysex` fail with `error`
    /// (one-shot — consumed by the failing call; the failed send is
    /// not recorded, matching a backend that rejected the message).
    pub fn fail_next_send(&self, error: DeviceError) {
        self.lock().send_error = Some(error);
    }

    /// Whether `open` has succeeded at least once.
    #[must_use]
    pub fn is_open(&self) -> bool {
        self.lock().opened
    }

    /// Whether `close` has run on the current subscription.
    #[must_use]
    pub fn is_closed(&self) -> bool {
        self.lock().closed
    }
}

impl MidiOutputPort for MockPort {
    fn info(&self) -> MidiOutputInfo {
        MockPort::info(self)
    }

    /// Opens the scripted subscription. A scripted `fail_next_open`
    /// error is consumed and returned once; a second `open` after a
    /// successful one is [`DeviceError::DeviceBusy`] — one handle
    /// opens at most once, per the port contract.
    fn open(&self) -> DeviceResult<Box<dyn MidiOutput>> {
        let mut state = self.lock();
        if let Some(error) = state.open_error.take() {
            return Err(error);
        }
        if state.opened {
            return Err(DeviceError::DeviceBusy);
        }
        state.opened = true;
        Ok(Box::new(MockOutput {
            state: Arc::clone(&self.state),
        }))
    }
}

/// The opened scripted subscription — appends to the shared port's
/// send record.
struct MockOutput {
    state: Arc<Mutex<PortState>>,
}

impl MockOutput {
    fn lock(&self) -> std::sync::MutexGuard<'_, PortState> {
        self.state.lock().expect("mock MIDI port state poisoned")
    }

    /// Shared send-path guard: closed subscriptions are dead, a
    /// scripted one-shot send error is consumed and returned without
    /// recording. Returns `Ok(())` when the send may be recorded.
    fn admit(&mut self) -> DeviceResult<()> {
        let mut state = self.lock();
        if state.closed {
            return Err(DeviceError::StreamInvalidated);
        }
        if let Some(error) = state.send_error.take() {
            return Err(error);
        }
        Ok(())
    }
}

impl MidiOutput for MockOutput {
    /// Records the event in send order. After `close`, sends fail
    /// with [`DeviceError::StreamInvalidated`] — the subscription is
    /// dead, matching a real backend whose handle was released.
    fn send(&mut self, event: MidiEvent) -> DeviceResult<()> {
        self.admit()?;
        self.lock().sent.push(event);
        Ok(())
    }

    /// Records the `SysEx` byte string in send order — same admission
    /// rules as [`Self::send`]. The mock does not validate `SysEx`
    /// framing; framing checks are the real backend's boundary job.
    fn send_sysex(&mut self, bytes: &[u8]) -> DeviceResult<()> {
        self.admit()?;
        self.lock().sent_sysex.push(bytes.to_vec());
        Ok(())
    }

    /// Marks the subscription closed — subsequent sends report
    /// [`DeviceError::StreamInvalidated`]. Idempotent.
    fn close(&mut self) {
        self.lock().closed = true;
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::midi_output::{MidiPortCapabilities, MidiPortOrigin};
    use ruviform_media_core::{
        MidiChannel, MidiController, MidiGroup, MidiKind, MidiProgram, MidiValue, NoteKey,
    };

    fn port_info(id: &str) -> MidiOutputInfo {
        MidiOutputInfo::new(
            id.to_owned(),
            format!("Mock Out {id}"),
            MidiPortOrigin::Virtual,
            MidiPortCapabilities::midi1_unstamped(),
        )
    }

    fn note_on(channel: u8, key: u8, velocity: u8) -> MidiEvent {
        MidiEvent {
            group: MidiGroup::ZERO,
            channel: MidiChannel::new(channel).unwrap(),
            kind: MidiKind::NoteOn {
                key: NoteKey::new(key).unwrap(),
                velocity: MidiValue::from_u7(velocity),
            },
        }
    }

    fn program_change(channel: u8, program: u8) -> MidiEvent {
        MidiEvent {
            group: MidiGroup::ZERO,
            channel: MidiChannel::new(channel).unwrap(),
            kind: MidiKind::ProgramChange {
                program: MidiProgram::new(program).unwrap(),
            },
        }
    }

    #[test]
    fn enumeration_returns_registered_ports_in_order() {
        let mut backend = MockBackend::new();
        backend.add_port(port_info("a"));
        backend.add_port(port_info("b"));
        assert_eq!(backend.port_count(), 2);

        let ports = backend.output_ports().unwrap();
        assert_eq!(ports.len(), 2);
        assert_eq!(ports[0].info().id, "a");
        assert_eq!(ports[1].info().id, "b");
        // Capabilities pass through verbatim — the engine reads them
        // to decide send policy, so the fixture must not soften them.
        assert!(!ports[0].info().capabilities.supports_ump);
        assert!(!ports[0].info().capabilities.provides_timestamps);
    }

    #[test]
    fn send_records_events_and_sysex_in_order() {
        let mut backend = MockBackend::new();
        let port = backend.add_port(port_info("p"));
        let cc = MidiEvent {
            group: MidiGroup::ZERO,
            channel: MidiChannel::new(0).unwrap(),
            kind: MidiKind::ControlChange {
                controller: MidiController::new(7).unwrap(),
                value: MidiValue::from_u7(100),
            },
        };

        let ports = backend.output_ports().unwrap();
        let mut output = ports[0].open().unwrap();
        assert!(port.is_open());

        output.send(note_on(0, 60, 100)).unwrap();
        output.send(cc).unwrap();
        output.send(program_change(0, 5)).unwrap();
        output.send_sysex(&[0xF0, 0x7E, 0x00, 0xF7]).unwrap();

        // Expected/Observed: the record is exactly the scripted send
        // sequence — independent expectation, not generated output.
        let expected = vec![note_on(0, 60, 100), cc, program_change(0, 5)];
        assert_eq!(port.sent_events(), expected);
        assert_eq!(port.sent_sysex(), vec![vec![0xF0, 0x7E, 0x00, 0xF7]]);
        assert_eq!(port.sent_count(), 4);

        port.clear_sent();
        assert_eq!(port.sent_count(), 0);

        output.close();
        assert!(port.is_closed());
        assert!(matches!(
            output.send(note_on(0, 60, 0)),
            Err(DeviceError::StreamInvalidated)
        ));
        assert!(matches!(
            output.send_sysex(&[0xF0, 0xF7]),
            Err(DeviceError::StreamInvalidated)
        ));
    }

    #[test]
    fn scripted_open_failure_is_consumed_once() {
        let mut backend = MockBackend::new();
        let port = backend.add_port(port_info("p"));
        port.fail_next_open(DeviceError::DeviceBusy);

        let ports = backend.output_ports().unwrap();
        assert!(matches!(ports[0].open(), Err(DeviceError::DeviceBusy)));
        // One-shot: the retry succeeds — models a transient backend
        // refusal the engine may legitimately retry.
        assert!(ports[0].open().is_ok());
    }

    #[test]
    fn second_open_is_busy() {
        let mut backend = MockBackend::new();
        let _port = backend.add_port(port_info("p"));
        let ports = backend.output_ports().unwrap();
        let _first = ports[0].open().unwrap();
        assert!(matches!(ports[0].open(), Err(DeviceError::DeviceBusy)));
    }

    #[test]
    fn scripted_send_failure_is_consumed_and_not_recorded() {
        let mut backend = MockBackend::new();
        let port = backend.add_port(port_info("p"));
        port.fail_next_send(DeviceError::StreamInvalidated);

        let ports = backend.output_ports().unwrap();
        let mut output = ports[0].open().unwrap();
        assert!(matches!(
            output.send(note_on(0, 60, 100)),
            Err(DeviceError::StreamInvalidated)
        ));
        // The failed send was rejected — nothing recorded.
        assert_eq!(port.sent_count(), 0);
        // One-shot consumed: the next send succeeds and records.
        output.send(note_on(0, 60, 100)).unwrap();
        assert_eq!(port.sent_events().len(), 1);
        // `fail_next_send` covers `send_sysex` too — same send path.
        port.fail_next_send(DeviceError::Xrun);
        assert!(matches!(
            output.send_sysex(&[0xF0, 0xF7]),
            Err(DeviceError::Xrun)
        ));
        assert_eq!(port.sent_sysex().len(), 0);
    }
}
