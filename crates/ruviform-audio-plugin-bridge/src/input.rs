//! Live MIDI input stage — the boundary between an open
//! [`MidiInput`] subscription and the plugin call's event stream.
//!
//! [`InputStage`] owns three things: a bounded `pending` buffer of
//! drained [`TimedMidiInput`]s, the published [`ClockAnchor`] that
//! maps their stamps to [`EngineFrame`]s, and a [`NoteLedger`]
//! tracking delivered note state so seek/stop can release everything
//! without stuck notes.
//!
//! ## Call model
//!
//! ```text
//! non-RT  input.read → pending (bounded, drop counted)
//! block   collect_block(block_start, frames, now, scratch)
//!         → &[Event]  (mapped offsets, late events clamped, rejects counted)
//! RT      merge_call_events(&[release, plan, live], scratch)
//!         → EventList → PluginEndpoint::process
//! ```
//!
//! - `read` is **non-RT**: it may lock the adapter's queue. Capacity
//!   is fixed at construction; overflow is counted, never silently
//!   dropped (`InputStageCounters::dropped_capacity`).
//! - `collect_block` is **RT-suitable**: bounded against `pending`'s
//!   fixed capacity and the caller's scratch — no allocation.
//! - `release_all` is **RT-suitable**: emits `NoteOff` events into a
//!   caller scratch, bounded by [`NOTE_LEDGER_CAPACITY`].
//!
//! Rejected stamps (unknown domain, anchor mismatch, overflow) are
//! counted in [`InputStageCounters`] and removed — an observable
//! defined rejection, not a stall.
//!
//! Contract source: `docs/specs/issue-188-timed-midi.md` (R4–R7),
//! `docs/designs/issue-188-timed-midi-detailed.md`.

use ruviform_audio_core::device::DeviceResult;
use ruviform_audio_core::midi_input::{MidiInput, MidiReadStats, TimedMidiInput};
use ruviform_media_core::{
    ClockAnchor, EngineFrame, MidiChannel, MidiEvent, MidiKind, MidiValue, NOTE_LEDGER_CAPACITY,
    NoteKey, NoteLedger, TimeBase, map_stamp_to_frame,
};
use ruviform_plugin_core::{Event, EventKind};
use ruviform_rt::{Consumer, Producer};

/// Fixed capacity of the `pending` drain buffer — events beyond it
/// are dropped and counted.
pub const INPUT_STAGE_CAPACITY: usize = 1024;

/// Cumulative, observable counters — the control/status surface for
/// input health. Read non-RT (control thread or status snapshot).
#[non_exhaustive]
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct InputStageCounters {
    /// Stamps successfully mapped to engine frames.
    pub mapped: u64,
    /// Events emitted into a delivered block list.
    pub delivered: u64,
    /// Events mapped before the current block start — delivered at
    /// offset 0 (defined late-event policy) and counted here.
    pub late: u64,
    /// Stamps that failed [`map_stamp_to_frame`] (unmapped domain,
    /// anchor mismatch, arithmetic overflow) — dropped, observable.
    pub rejected: u64,
    /// Events the backend reported dropping before `read`.
    pub dropped_backend: u64,
    /// Messages the backend received but could not translate into the
    /// declared channel-voice vocabulary (`MidiReadStats::unsupported`
    /// — `SysEx`, system common/realtime, malformed bytes). Excluded
    /// by design, not an overload signal — counted separately from
    /// [`Self::dropped_backend`].
    pub unsupported_backend: u64,
    /// Events dropped because `pending` was full.
    pub dropped_capacity: u64,
    /// `NoteOff` events generated by `release_all` (seek/stop/reset).
    pub released: u64,
    /// Times the [`NoteLedger`] force-released a note on overflow.
    pub ledger_overflows: u64,
}

/// Per-block summary returned by [`InputStage::collect_block`].
#[non_exhaustive]
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct BlockInputStats {
    /// Events written to `scratch` for this block.
    pub emitted: u32,
    /// Late events clamped to offset 0 this block.
    pub late: u32,
    /// Events consumed from `pending` this block.
    pub consumed: u32,
}

/// Live-input stage state — see module docs for the call model.
///
/// **RT contract:** `read`/`publish_anchor`/`attach` are non-RT;
/// `collect_block`/`release_all` are RT-suitable (bounded, no
/// allocation — all storage is fixed at construction).
pub struct InputStage {
    pending: Vec<TimedMidiInput>,
    anchor: Option<ClockAnchor>,
    /// Sample-clock timebase the anchor maps into — set at
    /// construction from the engine's stream rate.
    frame_base: TimeBase,
    ledger: NoteLedger,
    release_scratch: [MidiEvent; NOTE_LEDGER_CAPACITY],
    counters: InputStageCounters,
}

impl InputStage {
    /// Empty stage — `pending` pre-allocated to
    /// [`INPUT_STAGE_CAPACITY`]; `frame_base` is the engine
    /// sample-clock timebase (e.g. `TimeBase::new(1, 48_000)`).
    ///
    /// **RT contract:** non-RT — allocates once at construction.
    ///
    /// # Panics
    ///
    /// Never — the scratch seed values are statically in range;
    /// `unwrap` is unreachable.
    #[must_use]
    pub fn new(frame_base: TimeBase) -> Self {
        Self {
            pending: Vec::with_capacity(INPUT_STAGE_CAPACITY),
            anchor: None,
            frame_base,
            ledger: NoteLedger::new(),
            release_scratch: core::array::from_fn(|_| MidiEvent {
                group: ruviform_media_core::MidiGroup::ZERO,
                channel: MidiChannel::new(0).unwrap(),
                kind: MidiKind::NoteOff {
                    key: NoteKey::new(60).unwrap(),
                    velocity: MidiValue::from_u7(0),
                },
            }),
            counters: InputStageCounters::default(),
        }
    }

    /// Publish (or clear) the stamp→frame anchor — non-RT calibration
    /// published as a snapshot for the RT read path.
    ///
    /// **RT contract:** non-RT — called by the control thread before
    /// blocks start or after re-calibration.
    pub fn publish_anchor(&mut self, anchor: Option<ClockAnchor>) {
        self.anchor = anchor;
    }

    /// Drain the subscription into `pending` — non-RT.
    ///
    /// Bounded by remaining capacity; events that do not fit are
    /// counted (`dropped_capacity`) and *also* discarded by the
    /// adapter's own queue semantics — they are never silent since
    /// both sides count.
    ///
    /// **RT contract:** non-RT — may lock the adapter queue; no
    /// allocation beyond `pending`'s fixed capacity.
    ///
    /// # Errors
    ///
    /// [`ruviform_audio_core::device::DeviceError`] from the input.
    pub fn read(&mut self, input: &mut dyn MidiInput) -> DeviceResult<MidiReadStats> {
        let spare = INPUT_STAGE_CAPACITY - self.pending.len();
        let stats = input.read(&mut self.pending, spare)?;
        // The adapter may append at most `spare`; anything beyond its
        // own budget is its drop, reported via `stats.dropped`.
        self.counters.dropped_backend += stats.dropped;
        // Received-but-untranslatable traffic is observable too —
        // never let it die at the port boundary.
        self.counters.unsupported_backend += stats.unsupported;
        Ok(stats)
    }

    /// Drop `n` events that did not fit `pending` — counted so the
    /// consumer can attribute the loss instead of the adapter.
    ///
    /// **RT contract:** non-RT — bookkeeping only.
    pub fn report_capacity_drop(&mut self, n: u64) {
        self.counters.dropped_capacity += n;
    }

    /// Move queued events from the RT-side SPSC channel into
    /// `pending` — bounded by remaining capacity. Events that do not
    /// fit stay in the channel (backpressure toward the producer,
    /// never silently dropped); they are pumped on a later block.
    ///
    /// Returns the number of events moved.
    ///
    /// **RT contract:** RT-suitable — bounded `try_pop` loop, no
    /// allocation (`pending` was pre-allocated to
    /// [`INPUT_STAGE_CAPACITY`]).
    pub fn pump(&mut self, rx: &mut Consumer<TimedMidiInput>) -> u32 {
        let mut moved = 0u32;
        while self.pending.len() < INPUT_STAGE_CAPACITY {
            match rx.try_pop() {
                Ok(event) => {
                    self.pending.push(event);
                    moved += 1;
                }
                Err(_) => break,
            }
        }
        moved
    }

    /// Emit this block's live events into `scratch`, returning the
    /// written slice and per-block stats.
    ///
    /// Events whose mapped frame falls inside
    /// `[block_start, block_start + block_frames)` are written as
    /// call-relative `Event::new(offset, EventKind::Midi(..))` in
    /// arrival order — `pending` is drained FIFO, so same-tick input
    /// order is preserved. Late events (mapped frame before
    /// `block_start`, e.g. a stamp delivered after its block ran) are
    /// clamped to offset 0 and counted — an explicit, observable
    /// degradation rather than a dropped note. Events mapping past
    /// this block stay pending for a later block.
    ///
    /// Emitted note events update the [`NoteLedger`] so
    /// [`Self::release_all`] knows what is active; a ledger overflow
    /// force-release is counted (`ledger_overflows`).
    ///
    /// **RT contract:** RT-suitable — bounded by `pending` capacity
    /// and `scratch.len()`; no allocation.
    pub fn collect_block<'a>(
        &mut self,
        block_start: EngineFrame,
        block_frames: u32,
        now: EngineFrame,
        scratch: &'a mut [Event],
    ) -> (&'a mut [Event], BlockInputStats) {
        let mut emitted = 0usize;
        let mut late = 0u32;
        let mut consumed = 0usize;
        let mut w = 0usize;
        for r in 0..self.pending.len() {
            let input = self.pending[r];
            if emitted == scratch.len() {
                // Scratch exhausted — keep this and everything after;
                // the shortfall stays pending and is re-attempted.
                break;
            }
            let Some(anchor) = &self.anchor else {
                // No published anchor — nothing can map; leave events
                // pending rather than dropping them blind.
                break;
            };
            let keep = match map_stamp_to_frame(&input.stamp, anchor, self.frame_base, now) {
                Err(_) => {
                    self.counters.rejected += 1;
                    consumed += 1;
                    false
                }
                Ok(mapped) if !mapped.frame.same_epoch(block_start) => {
                    // Stale epoch — the stamp belongs to a clock era
                    // the engine already left; reject, don't relive it.
                    self.counters.rejected += 1;
                    consumed += 1;
                    false
                }
                Ok(mapped) => {
                    match mapped.frame.checked_offset(block_start) {
                        None => {
                            // Same epoch, mapped before this block —
                            // late delivery at offset 0 (explicit,
                            // observable degradation).
                            self.counters.mapped += 1;
                            late += 1;
                            scratch[emitted] = Event::new(0, EventKind::Midi(input.event));
                            emitted += 1;
                            consumed += 1;
                            self.ledger.feed(&input.event);
                            if self.ledger.take_overflow() {
                                self.counters.ledger_overflows += 1;
                            }
                            false
                        }
                        Some(off) if off < u64::from(block_frames) => {
                            self.counters.mapped += 1;
                            scratch[emitted] = Event::new(
                                u32::try_from(off).unwrap_or(u32::MAX),
                                EventKind::Midi(input.event),
                            );
                            emitted += 1;
                            consumed += 1;
                            self.ledger.feed(&input.event);
                            if self.ledger.take_overflow() {
                                self.counters.ledger_overflows += 1;
                            }
                            false
                        }
                        // Future block — keep pending.
                        Some(_) => true,
                    }
                }
            };
            if keep {
                self.pending[w] = input;
                w += 1;
            }
        }
        // Move events left unscanned by an early `break` down behind
        // the kept prefix — O(n) single pass, allocation-free.
        let scanned = consumed + w;
        for r in scanned..self.pending.len() {
            self.pending[w] = self.pending[r];
            w += 1;
        }
        self.pending.truncate(w);
        self.counters.delivered += emitted as u64;
        self.counters.late += u64::from(late);
        (
            &mut scratch[..emitted],
            BlockInputStats {
                emitted: u32::try_from(emitted).unwrap_or(u32::MAX),
                late,
                consumed: u32::try_from(consumed).unwrap_or(u32::MAX),
            },
        )
    }

    /// Emit `NoteOff` `Event`s at `offset` for every active note —
    /// seek/stop/state-reset handling (R6). Consumes the ledger.
    ///
    /// Returns the written slice; overflow in `scratch` truncates the
    /// release list and the leftover notes stay active — the count is
    /// observable via [`Self::active_notes`].
    ///
    /// **RT contract:** RT-suitable — bounded, no allocation.
    pub fn release_all<'a>(&mut self, offset: u32, scratch: &'a mut [Event]) -> &'a mut [Event] {
        let n = self
            .ledger
            .release_all(&mut self.release_scratch)
            .min(scratch.len());
        for (dst, midi) in scratch[..n].iter_mut().zip(&self.release_scratch[..n]) {
            *dst = Event::new(offset, EventKind::Midi(*midi));
        }
        self.counters.released += n as u64;
        &mut scratch[..n]
    }

    /// Active notes currently tracked — stuck-note observability.
    ///
    /// **RT contract:** RT-suitable — read-only.
    #[must_use]
    pub fn active_notes(&self) -> usize {
        self.ledger.active_count()
    }

    /// Events still pending (unmapped/future/unread) — backlog
    /// observability.
    ///
    /// **RT contract:** RT-suitable — read-only.
    #[must_use]
    pub fn pending_count(&self) -> usize {
        self.pending.len()
    }

    /// Cumulative counters — control/status surface.
    ///
    /// **RT contract:** RT-suitable — read-only.
    #[must_use]
    pub fn counters(&self) -> InputStageCounters {
        self.counters
    }
}

impl core::fmt::Debug for InputStage {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("InputStage")
            .field("pending", &self.pending.len())
            .field("active_notes", &self.ledger.active_count())
            .field("counters", &self.counters)
            .finish_non_exhaustive()
    }
}

/// Configuration for a node's live-MIDI input leg
/// ([`crate::AttachConfig::input`]). `channel_capacity` is the
/// non-RT→RT handoff depth; it is capped at [`INPUT_STAGE_CAPACITY`],
/// the stage's `pending` bound — deeper buys nothing.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct InputConfig {
    /// Events the handoff channel may hold before backpressure defers
    /// the pump. `0` or `> INPUT_STAGE_CAPACITY` is a defined
    /// [`crate::AttachError::InputConfig`] rejection.
    pub channel_capacity: usize,
}

impl InputConfig {
    /// A channel capacity equal to the stage's pending bound.
    ///
    /// **RT contract:** non-RT — declarative.
    #[must_use]
    pub const fn new(channel_capacity: usize) -> Self {
        Self { channel_capacity }
    }
}

/// Per-call observation returned by [`InputTx::pump`].
#[non_exhaustive]
#[derive(Copy, Clone, Debug, Default, PartialEq, Eq)]
pub struct PumpStats {
    /// Events `read` appended to the staging buffer this call.
    pub received: usize,
    /// Events pushed into the RT channel this call.
    pub pushed: usize,
    /// Events still staged afterwards (channel full — delivered on a
    /// later `pump`; not lost).
    pub deferred: usize,
    /// Events the backend reported dropping inside `read` this call.
    pub backend_dropped: u64,
    /// Messages the backend received but could not translate into the
    /// declared channel-voice vocabulary this call
    /// (`MidiReadStats::unsupported`). Excluded-by-design traffic,
    /// counted separately from [`Self::backend_dropped`].
    pub backend_unsupported: u64,
}

/// The non-RT producer half of a node's live-input leg: drains a
/// [`MidiInput`] subscription into a bounded staging buffer and pushes
/// staged events into the node's SPSC channel. Obtained from
/// [`crate::Attached::input_tx`].
///
/// The pump never drops events itself: a full channel defers staged
/// events to the next `pump` (backpressure), and a full staging buffer
/// stops `read` early — loss happens only inside the backend's own
/// bounded queue, observable via [`PumpStats::backend_dropped`] and
/// the cumulative [`Self::dropped_backend`]. Messages the backend
/// could not translate are observable the same way via
/// [`PumpStats::backend_unsupported`] / [`Self::unsupported_backend`].
///
/// **RT contract:** non-RT only — owns the producer endpoint and a
/// staging `Vec` pre-allocated to [`INPUT_STAGE_CAPACITY`]; `pump` may
/// lock the adapter's internal queue.
pub struct InputTx {
    tx: Producer<TimedMidiInput>,
    staging: Vec<TimedMidiInput>,
    dropped_backend: u64,
    unsupported_backend: u64,
}

impl InputTx {
    /// Pairs with the node's channel consumer — `attach` constructs.
    ///
    /// **RT contract:** non-RT — allocates the staging buffer.
    pub(crate) fn new(tx: Producer<TimedMidiInput>) -> Self {
        Self {
            tx,
            staging: Vec::with_capacity(INPUT_STAGE_CAPACITY),
            dropped_backend: 0,
            unsupported_backend: 0,
        }
    }

    /// Flush staged events into the channel, top up the staging buffer
    /// from `input`, then flush again — preserving arrival order
    /// end-to-end.
    ///
    /// Bounded by [`INPUT_STAGE_CAPACITY`] on both sides; excess input
    /// stays in the backend queue (its own drop counter reports it),
    /// excess staged events wait for channel space.
    ///
    /// **RT contract:** non-RT — may lock the adapter queue.
    ///
    /// # Errors
    ///
    /// [`ruviform_audio_core::device::DeviceError`] from the input's
    /// `read`; already-pushed events remain delivered.
    pub fn pump(&mut self, input: &mut dyn MidiInput) -> DeviceResult<PumpStats> {
        let mut pushed = 0usize;
        let mut kept = self.flush(&mut pushed);
        let spare = INPUT_STAGE_CAPACITY - kept;
        let stats = input.read(&mut self.staging, spare)?;
        let received = self.staging.len() - kept;
        self.dropped_backend += stats.dropped;
        self.unsupported_backend += stats.unsupported;
        kept = self.flush(&mut pushed);
        Ok(PumpStats {
            received,
            pushed,
            deferred: kept,
            backend_dropped: stats.dropped,
            backend_unsupported: stats.unsupported,
        })
    }

    /// Push staged events into the channel until it fills; returns the
    /// number still staged afterwards.
    fn flush(&mut self, pushed: &mut usize) -> usize {
        let mut kept = 0usize;
        for r in 0..self.staging.len() {
            match self.tx.try_push(self.staging[r]) {
                Ok(()) => *pushed += 1,
                Err(full) => {
                    self.staging[kept] = full.into_inner();
                    kept += 1;
                }
            }
        }
        self.staging.truncate(kept);
        kept
    }

    /// Backend drops observed so far — cumulative observability for
    /// the control surface.
    ///
    /// **RT contract:** non-RT — read-only.
    #[must_use]
    pub const fn dropped_backend(&self) -> u64 {
        self.dropped_backend
    }

    /// Backend-reported untranslatable messages observed so far —
    /// cumulative observability for the control surface, tracked
    /// separately from [`Self::dropped_backend`] (excluded vocabulary
    /// traffic, not overload loss).
    ///
    /// **RT contract:** non-RT — read-only.
    #[must_use]
    pub const fn unsupported_backend(&self) -> u64 {
        self.unsupported_backend
    }

    /// Events currently staged waiting on channel space.
    ///
    /// **RT contract:** non-RT — read-only.
    #[must_use]
    pub fn deferred(&self) -> usize {
        self.staging.len()
    }
}
